def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _safe_confined_write(anchor: pathlib.Path, target_dir: pathlib.Path,
                         filename: str, content: bytes,
                         exclusive: bool = False) -> None:
    """
    Write <target_dir>/<filename> WITHOUT following any symlink in the path from
    <anchor> down to and including the final file, and WITHOUT truncating, writing
    through, or following a symlink / hardlink / FIFO planted as the final name.

    <anchor> MUST be a trusted, already-resolved (symlink-free) root. The path is
    walked component-by-component with openat()+O_NOFOLLOW, so a symlink anywhere
    in the chain — an INTERMEDIATE directory just as much as the final component —
    raises OSError and aborts the write (closing the full path-traversal TOCTOU;
    O_NOFOLLOW on a single open only guards the last component). Missing directory
    components are created via mkdir() relative to the pinned parent fd.

    The final write avoids the O_TRUNC-at-open clobber: O_TRUNC truncates BEFORE
    any fstat can run, so a hardlink planted as <filename> (which O_NOFOLLOW does
    NOT catch and which IS a regular file, so an S_ISREG check passes) would have
    its external victim inode emptied. Instead:
      - exclusive=True  → O_CREAT|O_EXCL (atomic create-or-skip; refuses ANY
        existing node — regular/symlink/hardlink/FIFO — with FileExistsError).
      - exclusive=False → write a fresh O_EXCL temp in the pinned dir, then
        renameat() it over <filename>. rename replaces only the directory entry;
        it never follows/truncates/writes-through a planted node, so no victim
        inode can be clobbered and there is no race window.
    O_NONBLOCK + S_ISREG + st_nlink==1 refuse a FIFO/device/hardlink target.
    """
    rel_parts = target_dir.relative_to(anchor).parts
    if not rel_parts:
        raise OSError("refusing to write directly into the trusted anchor")

    # anchor is .resolve()'d (canonical, symlink-free) — the trust root.
    dir_fd = os.open(str(anchor), os.O_RDONLY | os.O_DIRECTORY)
    try:
        for part in rel_parts:
            try:
                next_fd = os.open(
                    part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=dir_fd
                )
            except FileNotFoundError:
                # Create the missing component relative to the pinned parent fd,
                # then re-open it with O_NOFOLLOW (a race-swap to a symlink in the
                # gap makes this re-open fail closed).
                os.mkdir(part, 0o755, dir_fd=dir_fd)
                next_fd = os.open(
                    part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=dir_fd
                )
            os.close(dir_fd)
            dir_fd = next_fd
        # dir_fd now pins the real target_dir, reached without traversing a symlink.
        if exclusive:
            # Atomic create-or-skip: O_EXCL refuses ANY existing node (regular file,
            # symlink, hardlink, FIFO, dir) → FileExistsError (caller: "already there,
            # skip"). A fresh O_EXCL inode is regular + single-link by construction.
            file_fd = os.open(
                filename,
                os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_NONBLOCK,
                0o644, dir_fd=dir_fd,
            )
            try:
                st = os.fstat(file_fd)
                if not stat.S_ISREG(st.st_mode) or st.st_nlink != 1:
                    raise OSError(f"{filename} is not a fresh regular file; refusing to write.")
                os.write(file_fd, content)
            finally:
                os.close(file_fd)
        else:
            # Refuse to overwrite anything that is not already a plain single-link
            # regular file: a symlink / hardlink / FIFO / device planted as <filename>
            # is skipped (OSError), not silently replaced. lstat() does not follow it.
            # Best-effort gate: a post-lstat race is still SAFE because the write goes
            # to a fresh temp + renameat (below), never opening/truncating the entry.
            try:
                est = os.lstat(filename, dir_fd=dir_fd)
            except FileNotFoundError:
                est = None
            if est is not None and (not stat.S_ISREG(est.st_mode) or est.st_nlink != 1):
                raise OSError(f"{filename} is not a plain regular file; refusing to overwrite.")
            # Atomic overwrite via fresh-temp + renameat: never opens/truncates the
            # existing entry, so even a node raced in after the lstat cannot be
            # followed, truncated (the O_TRUNC-at-open clobber), or written through.
            # renameat replaces only the directory entry (relative to the pinned dir-fd).
            tmp = f".{filename}.{os.urandom(8).hex()}.tmp"
            file_fd = os.open(
                tmp,
                os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_NONBLOCK,
                0o644, dir_fd=dir_fd,
            )
            try:
                try:
                    st = os.fstat(file_fd)
                    if not stat.S_ISREG(st.st_mode) or st.st_nlink != 1:
                        raise OSError("temp file is not a fresh regular file; refusing to write.")
                    os.write(file_fd, content)
                finally:
                    os.close(file_fd)
                os.rename(tmp, filename, src_dir_fd=dir_fd, dst_dir_fd=dir_fd)
            except BaseException:
                # any failure (fstat / write / rename) → remove the temp; never leak litter
                try:
                    os.unlink(tmp, dir_fd=dir_fd)
                except OSError:
                    pass
                raise
    finally:
        os.close(dir_fd)


def _safe_confined_read(anchor: pathlib.Path, target_dir: pathlib.Path,
                        filename: str):
    """
    Read <target_dir>/<filename> WITHOUT following any symlink in the path from
    <anchor> (trusted, already-resolved) down to and including the final file.

    Mirror of _safe_confined_write: walks every component with openat()+O_NOFOLLOW.
    Returns the file's UTF-8 text, or None if the file (or its .claude parent) is
    absent. Raises OSError if any component — intermediate dir or the final file —
    is a symlink/unsafe, so a read cannot be raced into following a symlink to an
    external file (a TOCTOU information-disclosure via the printed diff). The
    caller treats OSError as SKIP, exactly like the write path.
    """
    rel_parts = target_dir.relative_to(anchor).parts
    if not rel_parts:
        raise OSError("refusing to read directly from the trusted anchor")

    dir_fd = os.open(str(anchor), os.O_RDONLY | os.O_DIRECTORY)
    try:
        for part in rel_parts:
            try:
                next_fd = os.open(
                    part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=dir_fd
                )
            except FileNotFoundError:
                return None  # .claude (or an intermediate) absent → no existing adapter
            os.close(dir_fd)
            dir_fd = next_fd
        try:
            # O_NONBLOCK so a FIFO/device planted as settings.json cannot make the
            # open block forever (a local DoS); the S_ISREG check then refuses any
            # non-regular file outright. O_NONBLOCK is a no-op for regular files.
            file_fd = os.open(
                filename, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=dir_fd
            )
        except FileNotFoundError:
            return None
        try:
            st = os.fstat(file_fd)
            if not stat.S_ISREG(st.st_mode) or st.st_nlink != 1:
                # st_nlink>1 ⇒ a hardlink: O_NOFOLLOW does not catch it and it IS a
                # regular file, so without this check its (external) bytes would leak
                # into the printed diff. Refuse it.
                raise OSError(f"{filename} is not a regular single-link file; refusing to read.")
            chunks = []
            while True:
                buf = os.read(file_fd, 65536)
                if not buf:
                    break
                chunks.append(buf)
            return b"".join(chunks).decode("utf-8")
        finally:
            os.close(file_fd)
    finally:
        os.close(dir_fd)


def _load_canonical() -> dict:
    """Load and return the hooks block from the workspace-root settings.json."""
    if not CANONICAL_SETTINGS.exists():
        sys.exit(f"ERROR: canonical settings not found: {CANONICAL_SETTINGS}")
    with CANONICAL_SETTINGS.open() as f:
        data = json.load(f)
    if "hooks" not in data:
        sys.exit(f"ERROR: no 'hooks' key in {CANONICAL_SETTINGS}")
    return data["hooks"]


# Only the RESTRICTIVE lists travel to the adapters: an `allow` written for the workspace
# root must never widen what a project session may do without asking.
PROPAGATED_PERMISSION_KEYS = ("deny", "ask")


def _load_canonical_permissions() -> dict:
    """Return the canonical permissions block (deny/ask only); {} when the root has none.

    WHY (founder ruling Q2b, 2026-10-05; CRUMBLES 'L0 WRITE-GUARD SCOPE GAP', 2026-09-02):
    Claude Code reads the shared .claude/settings.json only from the session's primary
    working directory, so the root's L0 deny rules reached root-rooted sessions only; the
    adapters carried hooks and NO permissions, and an Edit/Write tool call on
    PAICodeConstitution-2026.md from any project-rooted session was denied by nothing."""
    with CANONICAL_SETTINGS.open() as f:
        perms = json.load(f).get("permissions") or {}
    return {k: list(perms[k]) for k in PROPAGATED_PERMISSION_KEYS if perms.get(k)}


def _absolutize_rule(rule: str) -> str:
    """Rewrite one `Tool(path)` rule so it names the same files from ANY working directory.

    Claude Code resolves `/x` against the settings file's own directory and a bare `x` /
    `./x` / `**/x` against the session cwd — both mean the workspace root when written in the
    root file, and something else (or nothing) inside a project adapter. `//abs` and `~/x`
    are already cwd-independent (the `//` form is the one the P3 canary proved, see
    mimo/test_mimo_seat.py). A rule with no path (a bare tool name) is refused: copied into
    every project it would gate that whole tool fleet-wide, which is never what a
    root-scoped file rule meant."""
    if not (rule.endswith(")") and "(" in rule):
        raise ValueError(f"permission rule has no path, not propagated: {rule!r}")
    tool, spec = rule[:-1].split("(", 1)
    if spec.startswith("//") or spec.startswith("~/"):
        return rule
    root = str(ROOT).strip("/")
    if spec.startswith("/"):
        return f"{tool}(//{root}{spec})"
    if spec.startswith("./"):
        spec = spec[2:]
    return f"{tool}(//{root}/{spec})"


def _permissions_with_absolute_paths(perms: dict) -> dict:
    return {k: [_absolutize_rule(r) for r in rules] for k, rules in perms.items()}


def _lint_permissions(perms: dict) -> list:
    """Every propagated rule must be cwd-independent (`//` or `~/`) — the observable the
    S4/CRUMBLES gap violated. A drift check cannot see a wrong-but-consistent rule."""
    problems = []
    for key, rules in perms.items():
        for rule in rules:
            spec = rule[:-1].split("(", 1)[1] if rule.endswith(")") and "(" in rule else ""
            if not (spec.startswith("//") or spec.startswith("~/")):
                problems.append(f"permissions.{key}: rule is not cwd-independent: {rule!r}")
    return problems


def _hooks_with_absolute_paths(hooks_block: dict) -> dict:
    """
    Return a deep-copy of the hooks block with all command strings resolved to
    absolute paths under HOOKS_DIR.

    The canonical source uses "$CLAUDE_PROJECT_DIR"/.claude/hooks/... — we
    replace the variable prefix with the absolute path to HOOKS_DIR.
    """
    import copy, re, shlex
    block = copy.deepcopy(hooks_block)

    def fix_cmd(cmd: str) -> str:
        # Matches quoted/unquoted and braced/unbraced $CLAUDE_PROJECT_DIR prefix variants
        # (the braced form shipped unrewritten until 2026-10-03, reviewer A S4-04).
        # plus any relative ./.claude/hooks/ reference.
        # The replacement must be SHELL-SAFE: the canonical form's quotes are consumed by the match, so a bare path
        # containing a space would split into two words and the hook would not run (S4 F4, 2026-10-08).
        # shlex.quote leaves a plain path untouched (byte-identical output) and quotes one with spaces.
        # A lambda, not a string: re.sub would otherwise interpret backslashes in the replacement.
        hooks_prefix = shlex.quote(str(HOOKS_DIR)) + "/"
        cmd = re.sub(
            r'"?\$\{?CLAUDE_PROJECT_DIR\}?"?/\.claude/hooks/',
            lambda _m: hooks_prefix,
            cmd,
        )
        # Already absolute (hand-copied adapters) — keep as-is
        return cmd

    for event_hooks in block.values():
        for entry in event_hooks:
            for hook in entry.get("hooks", []):
                if "command" in hook:
                    hook["command"] = fix_cmd(hook["command"])
    return block


def _lint_hook_commands(hooks_block: dict) -> list:
    """Return a list of problems with the (already rewritten) hook commands: an unresolved
    CLAUDE_PROJECT_DIR, or a program path that does not exist / is not executable. A drift
    check cannot see these (it compares generated text with generated text); this can."""
    import os, re, shlex
    problems = []
    for event, entries in hooks_block.items():
        for entry in entries:
            for hook in entry.get("hooks", []):
                cmd = hook.get("command")
                if not cmd:
                    continue
                if "CLAUDE_PROJECT_DIR" in cmd:
                    problems.append(f"{event}: unresolved CLAUDE_PROJECT_DIR in {cmd!r}")
                    continue
                try:
                    prog = shlex.split(cmd)[0]
                except (ValueError, IndexError):
                    problems.append(f"{event}: unparseable command {cmd!r}")
                    continue
                if not os.path.isabs(prog):
                    continue  # a bare name resolved through PATH: not lintable here
                if not os.path.exists(prog):
                    problems.append(f"{event}: program not found: {prog}")
                elif not os.access(prog, os.X_OK):
                    problems.append(f"{event}: program not executable: {prog}")
    return problems


def _build_adapter_content(hooks_block: dict, permissions: dict | None = None) -> str:
    """Return the JSON string for a project adapter settings.json."""
    payload = {
        "_generated_by": GENERATED_COMMENT,
        "hooks": hooks_block,
    }
    if permissions:
        payload["permissions"] = permissions
    return json.dumps(payload, indent=2) + "\n"


def _desired():
    """(desired adapter text, policy hash, absolute hooks, absolute permissions)."""
    canonical_hooks = _load_canonical()
    canonical_perms = _load_canonical_permissions()
    try:
        abs_perms = _permissions_with_absolute_paths(canonical_perms)
    except ValueError as e:
        sys.exit(f"ERROR: {e}")
    abs_hooks = _hooks_with_absolute_paths(canonical_hooks)
    policy_hash = _sha256(json.dumps({"hooks": canonical_hooks, "permissions": canonical_perms},
                                     sort_keys=True))
    return _build_adapter_content(abs_hooks, abs_perms), policy_hash, abs_hooks, abs_perms


def _discover_projects() -> list[pathlib.Path]:
    """
    Return a sorted list of unique project root dirs (parent of NEOCORTEX/ or
    BRAIN/) found within maxdepth MAX_DEPTH of ROOT, excluding ROOT itself
    and any governance/ or .claude/ subtrees.
    """
    found: set[pathlib.Path] = set()

    def _scan(current: pathlib.Path, depth: int):
        if depth > MAX_DEPTH:
            return
        try:
            entries = list(current.iterdir())
        except PermissionError:
            return
        for entry in entries:
            if not entry.is_dir():
                continue
            # Skip hidden dirs (except we already handled .claude at root),
            # and skip governance/ to avoid false positives.
            if entry.name.startswith("."):
                continue
            # NOTE 2026-08-25 (M-8, founder ruling): governance/ is NO LONGER skipped.
            # The regime root is a project by NEOCORTEX_SPEC's own definition (it has
            # NEOCORTEX/STATUS, JOURNAL, MANIFEST) and Art. 12 requires the enforcement
            # layer to audit itself. The prior exclusion's only rationale was "avoid false
            # positives"; a check of the tree found exactly ONE NEOCORTEX under governance/
            # — its own — so it guarded against nothing and cost the regime root its hooks
            # (verify_fires 2026-08-25: governance absent from 22 armed projects; the
            # standing "0 of 146 Stop-hook firings" anomaly was simply never-armed).
            # Arming writes settings.json with ABSOLUTE paths to the single canonical hook
            # set — no duplicate copy is created. Disarm escape: rm governance/.claude/settings.json
            if entry.name in STATE_DIR_NAMES:
                found.add(current)  # current is the project root
            else:
                _scan(entry, depth + 1)

    _scan(ROOT, 0)
    return sorted(found)


def _extra_target_status(rel: str) -> tuple[pathlib.Path, str | None]:
    """(path, refusal reason or None) for one EXTRA_TARGETS entry."""
    import subprocess
    path = ROOT / rel
    if not path.is_dir():
        return path, "not a directory"
    try:
        r = subprocess.run(["git", "-C", str(path), "check-ignore", "-q", ".claude/settings.json"],
                           capture_output=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired) as e:
        return path, f"git check-ignore could not run ({e})"
    if r.returncode != 0:
        return path, ".claude/settings.json is NOT git-ignored there (refusing: it could be published)"
    return path, None


def _targets() -> tuple[list[pathlib.Path], list[tuple[str, str]]]:
    """(armed targets = migrated projects + accepted extras, refused extras as (rel, reason))."""
    projects = _discover_projects()
    refused = []
    for rel in EXTRA_TARGETS:
        path, reason = _extra_target_status(rel)
        if reason:
            refused.append((rel, reason))
        elif path not in projects:
            projects.append(path)
    return sorted(projects), refused


